#!/usr/bin/env node
import { createCipheriv, randomBytes, scrypt as scryptCallback } from "node:crypto";
import { promisify } from "node:util";
import { mkdir, open, access } from "node:fs/promises";
import path from "node:path";
import { Wallet } from "ethers";
import { generateSeedPhrase } from "near-seed-phrase";
import bs58 from "bs58";

const scrypt = promisify(scryptCallback);
const OUT_DIR = path.resolve(process.cwd(), "wallet-output");
const SECRET_FILE = path.join(OUT_DIR, "afterstate-wallets.enc.json");
const PUBLIC_FILE = path.join(OUT_DIR, "afterstate-wallets.public.json");

function hiddenPrompt(label) {
  return new Promise((resolve, reject) => {
    if (!process.stdin.isTTY || !process.stdout.isTTY) {
      reject(new Error("Run this command in an interactive terminal so the password can be entered without echo."));
      return;
    }
    const stdin = process.stdin;
    const stdout = process.stdout;
    let value = "";
    stdout.write(label);
    stdin.setRawMode(true);
    stdin.resume();
    const onData = (chunk) => {
      for (const byte of chunk) {
        if (byte === 3) {
          cleanup();
          reject(new Error("Cancelled."));
          return;
        }
        if (byte === 13 || byte === 10) {
          stdout.write("\n");
          cleanup();
          resolve(value);
          return;
        }
        if (byte === 127 || byte === 8) {
          value = value.slice(0, -1);
          continue;
        }
        if (byte >= 32 && byte <= 126) value += String.fromCharCode(byte);
      }
    };
    function cleanup() {
      stdin.off("data", onData);
      stdin.setRawMode(false);
      stdin.pause();
    }
    stdin.on("data", onData);
  });
}

async function passwordPair() {
  const first = await hiddenPrompt("Create an encryption password (16+ characters): ");
  const second = await hiddenPrompt("Confirm encryption password: ");
  if (first.length < 16) throw new Error("Use at least 16 characters.");
  if (first !== second) throw new Error("Passwords do not match.");
  return first;
}

async function writeExclusive(file, contents) {
  const handle = await open(file, "wx", 0o600);
  try {
    await handle.writeFile(contents, "utf8");
    await handle.sync();
  } finally {
    await handle.close();
  }
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true, mode: 0o700 });
  for (const file of [SECRET_FILE, PUBLIC_FILE]) {
    try {
      await access(file);
      throw new Error(`Refusing to overwrite existing wallet output: ${file}`);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }

  const password = await passwordPair();

  // Wallet.createRandom uses Node's cryptographically secure random source.
  const evm = Wallet.createRandom();
  const near = generateSeedPhrase();
  const nearImplicitAccountId = Buffer.from(bs58.decode(near.publicKey.split(":")[1])).toString("hex");

  const secretPayload = {
    format: "afterstate-wallet-backup-v1",
    warning: "Private material. Never upload, commit, or share this file.",
    evm: {
      network: "Base Sepolia (84532) intended; key is not chain-specific",
      address: evm.address,
      derivationPath: evm.path,
      mnemonic: evm.mnemonic?.phrase,
      privateKey: evm.privateKey
    },
    near: {
      network: "NEAR testnet",
      publicKey: near.publicKey,
      implicitAccountId: nearImplicitAccountId,
      seedPhrase: near.seedPhrase,
      secretKey: near.secretKey
    }
  };

  const salt = randomBytes(16);
  const iv = randomBytes(12);
  const key = await scrypt(password, salt, 32, { N: 1 << 15, r: 8, p: 1, maxmem: 64 * 1024 * 1024 });
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  const ciphertext = Buffer.concat([
    cipher.update(JSON.stringify(secretPayload), "utf8"),
    cipher.final()
  ]);
  const encrypted = {
    format: "afterstate-encrypted-wallets-v1",
    kdf: { name: "scrypt", N: 32768, r: 8, p: 1, salt: salt.toString("base64") },
    cipher: { name: "aes-256-gcm", iv: iv.toString("base64"), tag: cipher.getAuthTag().toString("base64") },
    ciphertext: ciphertext.toString("base64")
  };

  const publicPayload = {
    project: "AfterState",
    purpose: "Dedicated testnet deployment identities",
    evm: { network: "Base Sepolia", chainId: 84532, address: evm.address },
    near: { network: "NEAR testnet", publicKey: near.publicKey, implicitAccountId: nearImplicitAccountId },
    notes: [
      "The EVM address is generated locally; it is not funded.",
      "The NEAR keypair is generated locally; a named NEAR testnet account still needs to be registered/funded.",
      "The NEAR-derived Chain Signatures EVM signer is a separate protocol identity and is not generated by this utility."
    ]
  };

  await writeExclusive(SECRET_FILE, JSON.stringify(encrypted, null, 2) + "\n");
  await writeExclusive(PUBLIC_FILE, JSON.stringify(publicPayload, null, 2) + "\n");

  console.log("\nWallet material generated locally.");
  console.log("EVM address:", evm.address);
  console.log("NEAR public key:", near.publicKey);
  console.log("NEAR implicit account ID:", nearImplicitAccountId);
  console.log("\nEncrypted backup:", SECRET_FILE);
  console.log("Public addresses:", PUBLIC_FILE);
  console.log("\nIMPORTANT: Keep wallet-output/afterstate-wallets.enc.json and its password offline.");
  console.log("Do not paste the password, seed phrases, or private keys into ChatGPT, GitHub, or Discord.");
  console.log("Share only the EVM address and NEAR public key/account ID.");
}

main().catch((error) => {
  console.error("Wallet setup failed:", error.message);
  process.exitCode = 1;
});
